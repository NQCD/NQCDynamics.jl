        @warn "No friction evaluation algorithm has been specified, the friction tensor will be empty"
    end

    return QuantumFrictionModel_Cache(
        model,
        friction_method,
        potential,
        derivative,
        eigen,
        phase_ref,
        adiabatic_derivative,
        nonadiabatic_coupling,

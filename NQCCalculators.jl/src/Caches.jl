    centroid = similar(matrix_prototype, ndofs(model), atoms)
    centroid_potential = similar(matrix_prototype, 1, 1)
    centroid_derivative = similar(matrix_prototype, ndofs(model), atoms)

    return RingPolymer_ClassicalModel_Cache(
        model,
        potential,
        derivative,

        centroid,
        centroid_potential,
        centroid_derivative
    )
end


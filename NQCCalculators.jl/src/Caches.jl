"""
function RingPolymer_ClassicalModel_Cache(model::M, atoms::Integer, beads::Integer, matrix_prototype::AbstractArray{T,N}) where {M<:Model, T, N}
    potential = [similar(matrix_prototype, 1, 1) for i in 1:beads]
